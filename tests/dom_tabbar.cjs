const assert=require('node:assert/strict'),fs=require('node:fs');
const {JSDOM}=require(process.env.SMETRA_JSDOM_MODULE||'jsdom');
const tick=()=>new Promise(resolve=>setTimeout(resolve,0));
(async()=>{
 const html=fs.readFileSync('apps/web/app.html','utf8');
 const bar=html.match(/<nav id="mobile-tabbar"[\s\S]*?<\/nav>/)[0];
 assert.deepEqual([...bar.matchAll(/data-tab="([a-z-]+)"/g)].map(m=>m[1]),['profile','quotes','assistant','billing','ar-scan'],'Tab bar keeps assistant, estimates and account controls available');
 assert.ok(/id="tabbar-ar"[^>]*data-tab="ar-scan"/.test(bar),'AR Scan is a routed tab');
 assert.doesNotMatch(bar,/tabbar-more|Ещё/,'The old More tab is removed');
 assert.ok(html.indexOf('/ui/tabbar.js')>html.indexOf('/app.js'),'Tab bar script loads after the router');
 const dom=new JSDOM(`<!doctype html><body>${bar}<input id="field"></body>`,{runScripts:'outside-only',url:'https://smetra.online/app#ar-scan'});
 const w=dom.window,d=w.document;
 w.eval(fs.readFileSync('apps/web/ui/tabbar.js','utf8'));
 const ar=d.querySelector('[data-tab="ar-scan"]');ar.classList.add('active');await tick();
 assert.equal(ar.getAttribute('aria-current'),'page','The active AR tab is announced');
 ar.classList.remove('active');
 const quotes=d.querySelector('[data-tab="quotes"]');quotes.classList.add('active');await tick();
 assert.equal(ar.hasAttribute('aria-current'),false);
 assert.equal(quotes.getAttribute('aria-current'),'page');
 dom.window.close();
 console.log('PASS: five mobile tabs, direct AR navigation and accessible active state');
})().catch(error=>{console.error(error);process.exit(1)});
