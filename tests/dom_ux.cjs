const assert=require('node:assert/strict'),fs=require('node:fs');
const {JSDOM}=require(process.env.SMETRA_JSDOM_MODULE||'jsdom');
const tick=()=>new Promise(resolve=>setTimeout(resolve,0));
(async()=>{
 const html=fs.readFileSync('apps/web/app.html','utf8');
 assert.ok(html.indexOf('/ui/ux.js')>html.indexOf('/app.js'),'Conveniences load after the router');
 const dom=new JSDOM(`<!doctype html><body><main id="content"><div class="topline"><div class="topline-actions"><button class="btn primary" id="create">Создать смету</button></div></div><input id="list-search" type="search"><form><label for="doc">Документ</label><input id="doc" type="file"><input id="hidden-file" type="file" hidden></form></main></body>`,{runScripts:'outside-only',url:'https://smetra.online/app#quotes',pretendToBeVisual:true});
 const w=dom.window,d=w.document;
 w.matchMedia=()=>({matches:false,addEventListener(){}});
 w.HTMLElement.prototype.getBoundingClientRect=function(){return{width:this.hidden?0:120,height:30,top:0,left:0,right:120,bottom:30}};
 w.HTMLElement.prototype.getClientRects=function(){return this.hidden?[]:[{}]};
 w.HTMLDialogElement&&(w.HTMLDialogElement.prototype.showModal=function(){this.setAttribute('open','')});
 w.eval(fs.readFileSync('apps/web/ui/ux.js','utf8'));
 const doc=d.querySelector('#doc'),pick=doc.nextElementSibling;
 assert.ok(pick?.classList.contains('file-pick'),'A visible file input gets the styled picker');
 assert.equal(pick.querySelector('.file-pick-button').textContent,'Выбрать файл');
 assert.equal(pick.querySelector('.file-pick-name').textContent,'Файл не выбран','No English browser text');
 assert.equal(pick.querySelector('.file-pick-button').getAttribute('aria-label'),'Выбрать файл: Документ');
 let opened=0;doc.click=()=>opened++;pick.querySelector('button').click();assert.equal(opened,1,'The button opens the system picker');
 assert.equal(d.querySelector('#hidden-file').nextElementSibling,null,'Hidden inputs keep their own trigger');
 const later=d.createElement('input');later.type='file';later.multiple=true;d.querySelector('form').append(later);await tick();
 assert.equal(later.nextElementSibling?.querySelector('button').textContent,'Выбрать файлы','Inputs added later are enhanced too');
 const key=(k,code,extra={})=>d.body.dispatchEvent(new w.KeyboardEvent('keydown',{key:k,code,bubbles:true,cancelable:true,...extra}));
 key('/','Slash');assert.equal(d.activeElement.id,'list-search','«/» focuses the section search');
 d.activeElement.blur();
 let created=0;d.querySelector('#create').onclick=()=>created++;
 key('т','KeyN');assert.equal(created,1,'«N» creates a record on any keyboard layout');
 d.querySelector('#list-search').focus();d.querySelector('#list-search').dispatchEvent(new w.KeyboardEvent('keydown',{key:'n',code:'KeyN',bubbles:true}));
 assert.equal(created,1,'Typing in a field never triggers shortcuts');
 d.activeElement.blur();key('?','Slash',{shiftKey:true});
 assert.ok(d.querySelector('dialog.keys-help[open]'),'«?» shows the shortcut list');
 assert.match(d.querySelector('.keys-help-list').textContent,/Быстрый переход/);
 console.log('PASS: Russian file picker, late inputs, «/», «N» and «?» shortcuts');
})().catch(error=>{console.error(error);process.exit(1)});
