/* Headless UI contract: calculator handoff is read-only until a user clicks. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {JSDOM}=require(process.env.SMETRA_JSDOM_MODULE||'jsdom');
const source=fs.readFileSync('apps/web/calculators.js','utf8');
(async()=>{
 const dom=new JSDOM('<!doctype html><html lang="ru"><body><main id="content"></main></body></html>',{url:'https://smetra.test/app#calculators',runScripts:'dangerously'});
 const w=dom.window,opened=[],notices=[];
 w.structuredClone=structuredClone;
 w.view=html=>{w.document.querySelector('#content').innerHTML=html};
 w.Workspace={editor:async draft=>{opened.push(draft)}};
 w.notify=message=>notices.push(String(message));
 w.eval(source);
 const app=w.SmetraCalculators;
 assert.equal(typeof app.estimateDraft,'function');
 app.render();
 const $=s=>w.document.querySelector(s);
 assert.ok($('#smetra-calculators'));
 assert.equal($('#smcalc-draft').disabled,false);
 assert.equal($('#smcalc-unit-mode').value,'material');
 assert.match($('#smcalc-draft-qty').textContent,/13,2 м²/);
 assert.equal(opened.length,0,'Displaying a calculation must never create a quote');

 const change=(element,value,type='input')=>{element.value=value;element.dispatchEvent(new w.Event(type,{bubbles:true}))};
 change($('#smcalc-form [name=length]'),'-1');
 assert.equal($('#smcalc-draft').disabled,true,'Invalid calculation cannot be transferred');
 assert.equal(opened.length,0);
 change($('#smcalc-form [name=length]'),'4');
 assert.equal($('#smcalc-draft').disabled,false);
 change($('#smcalc-unit-mode'),'packages','change');
 assert.match($('#smcalc-draft-qty').textContent,/10 упак/);
 $('#smcalc-draft').click();
 await new Promise(resolve=>setImmediate(resolve));
 assert.equal(opened.length,1,'Only the explicit click opens an editor');
 assert.equal(opened[0].items[0].quantity,'10');
 assert.equal(opened[0].items[0].unit,'упак.');
 assert.equal(opened[0].items[0].unit_price,0);
 assert.equal(opened[0].client,'');
 assert.ok(opened[0].items[0].description.includes('упаковки'));
 assert.equal(notices.length,0);

 $('[data-calc-kind=paint]').click();
 assert.equal($('#smcalc-unit-mode').value,'material','Changing calculators resets package mode');
 assert.match($('#smcalc-draft-qty').textContent,/2,64 л/);
 change($('#smcalc-unit-mode'),'packages','change');
 assert.match($('#smcalc-draft-qty').textContent,/2 банка/);
 $('#smcalc-draft').click();
 await new Promise(resolve=>setImmediate(resolve));
 assert.equal(opened.length,2);
 assert.equal(opened[1].items[0].quantity,'2');
 assert.equal(opened[1].items[0].unit,'банка');
 assert.equal(opened[1].items[0].unit_price,0);

 $('[data-calc-kind=concrete]').click();
 assert.equal($('#smcalc-unit-mode').disabled,true,'Concrete must not offer packaging');
 assert.match($('#smcalc-draft-qty').textContent,/1,575 м³/);
 assert.ok(!$('#smcalc-draft').disabled);
 assert.equal(opened.length,2,'Changing tabs cannot create a draft');
 dom.window.close();
 console.log('PASS: calculator preview, input validation, package mode, safe draft handoff and no implicit writes');
})().catch(error=>{console.error(error);process.exitCode=1});
